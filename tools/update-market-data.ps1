# Downloads WoW Forever AH prices from auctionhouse.fyi's public API and writes MarketData.lua
# next to the addon, for the Market Data tab. WoW addons can't go online, so this runs outside the game.
# After it finishes, type /reload in game.
param(
    [string]$OutFile = (Join-Path (Split-Path $PSScriptRoot -Parent) 'MarketData.lua'),
    [int]$HistoryDays = 30
)
$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
$base = 'https://auctionhouse.fyi/api/v1'
$headers = @{ 'User-Agent' = 'AHPriceTracker-addon (market data import)'; 'Accept-Encoding' = 'gzip' }
$markets = 'normal.horde', 'normal.alliance', 'pvp.horde', 'pvp.alliance', 'rp.horde', 'rp.alliance'

function Get-Json($url) {
    for ($try = 1; $try -le 3; $try++) {
        try { return Invoke-RestMethod -Uri $url -Headers $headers -TimeoutSec 60 }
        catch { if ($try -eq 3) { throw }; Start-Sleep -Seconds (3 * $try) }
    }
}
function LuaStr($s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"' -replace "`r|`n", ' ') + '"' }
function Sec($ms) { if ($null -eq $ms) { 'nil' } else { [string][int64]([double]$ms / 1000) } }
function Num($v) { if ($null -eq $v) { 'false' } else { [string][int64]$v } }
function NumF($v) { if ($null -eq $v) { 'false' } else { ([math]::Round([double]$v, 3)).ToString([Globalization.CultureInfo]::InvariantCulture) } }

Write-Host 'Downloading item catalogue (names, vendor prices)...'
# items: { "<id>": { n = name, q = quality, c = class, buy = vendor price, sell = price a vendor pays you } }
# variants: random-suffix gear, { "<key>": { n, q } }
$cat = Get-Json "$base/items"
$names = @{}
foreach ($p in $cat.items.PSObject.Properties) {
    $v = $p.Value
    $names[[int64]$p.Name] = @($v.n, $v.q, $v.buy, $v.sell, $v.c, $v.sc, $v.il, $null)
}
foreach ($p in $cat.variants.PSObject.Properties) {
    $names[[int64]$p.Name] = @($p.Value.n, $p.Value.q, $null, $null, $null, $null, $null, $null)
}

# Vendor prices from WoW Forever's own item table (wago.tools DB2 export). The catalogue's buy price is for
# a whole vendor bundle (Empty Vial: 20c for 5, arrows: 50c for 200), so divide by the bundle size to get
# the price of one item. The table is cached for a week; it only changes with game patches.
try {
    $cacheDir = Join-Path $PSScriptRoot 'cache'
    New-Item -ItemType Directory -Force $cacheDir | Out-Null
    $sparse = Join-Path $cacheDir 'ItemSparse.csv'
    if (-not (Test-Path $sparse) -or ((Get-Date) - (Get-Item $sparse).LastWriteTime).TotalDays -gt 7) {
        Write-Host 'Downloading game item table (vendor bundle sizes)...'
        $builds = Invoke-RestMethod -Uri 'https://wago.tools/api/builds' -Headers $headers -TimeoutSec 60
        $ver = @($builds.wowf)[0].version
        Invoke-WebRequest -Uri "https://wago.tools/db2/ItemSparse/csv?version=$ver" -Headers $headers -UseBasicParsing -TimeoutSec 300 -OutFile $sparse
    }
    $fixed = 0
    foreach ($row in (Import-Csv $sparse)) {
        $id = [int64]$row.ID
        $n = $names[$id]
        if (-not $n) { continue }
        $bundle = [math]::Max(1, [int]$row.VendorStackCount)
        $buy = [double]$row.BuyPrice
        if ($buy -gt 0) {
            $n[2] = $buy / $bundle
            if ($bundle -gt 1) { $n[7] = $bundle }
            if ($bundle -gt 1) { $fixed++ }
        }
        if ([double]$row.SellPrice -gt 0) { $n[3] = [double]$row.SellPrice }
    }
    Write-Host "Vendor prices set per item ($fixed items are sold in bundles)."
} catch {
    Write-Host "Couldn't read the game item table ($($_.Exception.Message)); vendor prices may be per bundle."
}

$sb = New-Object System.Text.StringBuilder
$now = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
[void]$sb.AppendLine('-- Generated by tools\update-market-data.ps1 from auctionhouse.fyi (player-sourced scans). Do not edit.')
[void]$sb.AppendLine('AHPT_MarketData = {')
[void]$sb.AppendLine("  source = `"auctionhouse.fyi`", generated = $now,")
[void]$sb.AppendLine('  markets = {')
$used = @{}
$summary = @()
foreach ($m in $markets) {
    Write-Host "Downloading $m..."
    $snap = Get-Json "$base/ah/forever.$m.us/snapshot"
    Start-Sleep -Milliseconds 500
    $hist = Get-Json "$base/ah/forever.$m.us/history?days=$HistoryDays"
    Start-Sleep -Milliseconds 500
    $days = @{}
    foreach ($h in @($hist.items)) { if ($h) { $days[[int64]$h[0]] = $h[1] } }

    [void]$sb.AppendLine("    [`"$m`"] = { scan = $(Sec $snap.scan), items = {")
    $count = 0
    foreach ($r in @($snap.rows)) {
        if (-not $r) { continue }
        $id = [int64]$r[0]
        $used[$id] = $true
        # day candles: day number (days since 1970), open, high, low, close, quantity -> keep low, close, qty
        $d = @()
        foreach ($c in @($days[$id])) { if ($c) { $d += "$([int]$c[0]),$(Num $c[3]),$(Num $c[4]),$(Num $c[5])" } }
        [void]$sb.AppendLine("      [$id] = { $(Num $r[1]), $(Num $r[2]), $(Sec $r[3]), { $($d -join ',') } },")
        $count++
    }
    [void]$sb.AppendLine('    } },')
    $when = if ($snap.scan) { [DateTimeOffset]::FromUnixTimeMilliseconds([int64]$snap.scan).LocalDateTime.ToString('g') } else { 'never' }
    $summary += ("{0,-16} {1,6} items   last scan {2}" -f $m, $count, $when)
}
[void]$sb.AppendLine('  },')
[void]$sb.AppendLine('  names = {')
foreach ($id in ($used.Keys | Sort-Object)) {
    $n = $names[$id]
    # Random-suffix gear ("of the Bear") uses key = suffix * 2^32 + itemID; keep the base item ID too.
    $baseId = $id % 4294967296
    # { name, quality, base item ID, vendor price per item, vendor sell price, class, subclass, item level, vendor bundle size }
    if ($n) { [void]$sb.AppendLine("    [$id] = { $(LuaStr $n[0]), $([int]$n[1]), $baseId, $(NumF $n[2]), $(Num $n[3]), $(Num $n[4]), $(Num $n[5]), $(Num $n[6]), $(Num $n[7]) },") }
}
[void]$sb.AppendLine('  },')
[void]$sb.AppendLine('}')

$tmp = "$OutFile.tmp"
[IO.File]::WriteAllText($tmp, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
Move-Item -Force $tmp $OutFile
Write-Host ''
$summary | ForEach-Object { Write-Host $_ }
Write-Host ''
Write-Host "Saved $OutFile ($([math]::Round((Get-Item $OutFile).Length / 1KB)) KB). Type /reload in game to load it."

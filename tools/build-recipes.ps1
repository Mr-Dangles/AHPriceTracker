# Builds Recipes.lua (every profession's recipes for WoW Forever) from the game's own data tables,
# published as CSV by wago.tools (product "wowf"), plus item names from auctionhouse.fyi.
# Only needs re-running after a game patch adds or changes recipes. Then /reload in game.
param(
    [string]$OutFile = (Join-Path (Split-Path $PSScriptRoot -Parent) 'Recipes.lua'),
    [string]$Product = 'wowf'
)
$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
$headers = @{ 'User-Agent' = 'AHPriceTracker-addon (recipe data build)' }
$tmp = Join-Path $env:TEMP 'ahpt-recipes'
New-Item -ItemType Directory -Force $tmp | Out-Null

# Exact build, so the file records what it was made from
$builds = Invoke-RestMethod -Uri 'https://wago.tools/api/builds' -Headers $headers
$version = @($builds.$Product)[0].version
if (-not $version) { throw "No builds found for product '$Product'." }
Write-Host "Game data build: $Product $version"

function Get-Table($name) {
    $file = Join-Path $tmp "$name.csv"
    Write-Host "Downloading $name..."
    Invoke-WebRequest -Uri "https://wago.tools/db2/$name/csv?version=$version" -Headers $headers -UseBasicParsing -TimeoutSec 300 -OutFile $file
    Start-Sleep -Milliseconds 500
    Import-Csv $file
}
function LuaStr($s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"' -replace "`r|`n", ' ') + '"' }

# Crafting professions (and their Forever sub-lines, whose ParentSkillLineID points at the main one)
$PROFS = @{
    171 = 'Alchemy'; 164 = 'Blacksmithing'; 185 = 'Cooking'; 333 = 'Enchanting'; 202 = 'Engineering'
    129 = 'First Aid'; 165 = 'Leatherworking'; 186 = 'Mining (Smelting)'; 197 = 'Tailoring'; 40 = 'Poisons (Rogue)'
}
$skillLines = Get-Table 'SkillLine'
$lineToProf = @{}
foreach ($id in $PROFS.Keys) { $lineToProf[[string]$id] = $id }
foreach ($l in $skillLines) {
    if ($l.ParentSkillLineID -and $PROFS.ContainsKey([int]$l.ParentSkillLineID)) { $lineToProf[$l.ID] = [int]$l.ParentSkillLineID }
}

$abilities = Get-Table 'SkillLineAbility' | Where-Object { $lineToProf.ContainsKey($_.SkillLine) }
$effects = @{}
foreach ($e in (Get-Table 'SpellEffect')) {
    if ($e.Effect -eq '24' -and $e.EffectItemType -ne '0') {
        $effects[$e.SpellID] = @([int]$e.EffectItemType, [math]::Max(1, [int][math]::Floor([double]$e.EffectBasePointsF)))
    }
}
$reagents = @{}
foreach ($r in (Get-Table 'SpellReagents')) {
    $list = @()
    for ($i = 0; $i -le 7; $i++) {
        $id = [int]$r."Reagent_$i"; $n = [int]$r."ReagentCount_$i"
        if ($id -gt 0 -and $n -gt 0) { $list += "$id,$n" }
    }
    if ($list.Count) { $reagents[$r.SpellID] = $list -join ',' }
}
$spellNames = @{}
foreach ($s in (Get-Table 'SpellName')) { $spellNames[$s.ID] = $s.Name_lang }

Write-Host 'Downloading item catalogue (names, recipe items)...'
$cat = Invoke-RestMethod -Uri 'https://auctionhouse.fyi/api/v1/items' -Headers $headers -TimeoutSec 120
$itemName = @{}; $recipeByName = @{}
foreach ($p in $cat.items.PSObject.Properties) {
    $itemName[[int]$p.Name] = $p.Value.n
    if ($p.Value.c -eq 9 -and $p.Value.n -match '^(Recipe|Pattern|Plans|Formula|Schematic|Manual): (.+)$') {
        $recipeByName[$Matches[2].ToLower()] = [int]$p.Name
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("-- Generated by tools\build-recipes.ps1 from game data ($Product $version via wago.tools). Do not edit.")
[void]$sb.AppendLine('AHPT_Recipes = {')
[void]$sb.AppendLine("  build = `"$version`",")
[void]$sb.AppendLine('  -- [profession] = { name, recipes = { { spell, name, minSkill, greenAt, greyAt, itemID, count, recipeItem, { reagentID, count, ... } }, ... } }')
[void]$sb.AppendLine('  professions = {')
$used = @{}
$summary = @()
$ORDER = 171, 164, 185, 333, 202, 129, 165, 186, 197, 40
foreach ($profId in $ORDER) {
    $rows = @(); $seen = @{}
    foreach ($a in $abilities) {
        if ($lineToProf[$a.SkillLine] -ne $profId) { continue }
        $sp = $a.Spell
        if ($seen[$sp] -or -not $effects.ContainsKey($sp)) { continue } # only recipes that make an item
        $seen[$sp] = $true
        $item, $count = $effects[$sp]
        $name = $spellNames[$sp]; if (-not $name) { $name = $itemName[$item] }
        if (-not $name -or $name -match 'DNT|\[PH\]|Test ') { continue }
        $recipeItem = $recipeByName[[string]$name.ToLower()]
        $used[$item] = $true
        $rg = $reagents[$sp]; if (-not $rg) { $rg = '' }
        foreach ($x in ($rg -split ',' | Where-Object { $_ } | Select-Object -Index (0..15 | Where-Object { $_ % 2 -eq 0 }))) { $used[[int]$x] = $true }
        $rows += "      { $sp, $(LuaStr $name), $([int]$a.MinSkillLineRank), $([int]$a.TrivialSkillLineRankLow), $([int]$a.TrivialSkillLineRankHigh), $item, $count, $(if ($recipeItem) { $recipeItem } else { 'false' }), { $rg } },"
    }
    [void]$sb.AppendLine("    [$profId] = { name = $(LuaStr $PROFS[$profId]), recipes = {")
    foreach ($row in $rows) { [void]$sb.AppendLine($row) }
    [void]$sb.AppendLine('    } },')
    $summary += ('{0,-20} {1,4} recipes' -f $PROFS[$profId], $rows.Count)
}
[void]$sb.AppendLine('  },')
[void]$sb.AppendLine('  names = {')
foreach ($id in ($used.Keys | Sort-Object)) {
    if ($itemName[$id]) { [void]$sb.AppendLine("    [$id] = $(LuaStr $itemName[$id]),") }
}
[void]$sb.AppendLine('  },')
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($OutFile, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
$summary | ForEach-Object { Write-Host $_ }
Write-Host "Saved $OutFile. Type /reload in game."
